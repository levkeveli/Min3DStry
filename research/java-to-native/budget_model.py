#!/usr/bin/env python3
"""Memory and cycle budget model for the Min3DStry feasibility study (issue #1).

These are explicit *models*, not measurements. Every constant below is an
assumption that can be changed; the script prints the arithmetic so reviewers
can check it. Hardware constants come from 3dbrew (see
docs/research/java-to-native.md). Evidence level: host-computed, not-tested on
3DS hardware.

Usage:
    python3 budget_model.py            # markdown report
    python3 budget_model.py --json     # machine-readable summary
"""

from __future__ import annotations

import argparse
import json

MIB = 1024 * 1024

# 3dbrew Memory layout: APPLICATION region sizes.
APP_REGIONS = (
    ("Old 3DS/2DS (APPMEMTYPE 0)", 64 * MIB),
    ("New 3DS/2DS default (APPMEMTYPE 6)", 124 * MIB),
    ("New 3DS 2x mode (APPMEMTYPE 7)", 178 * MIB),
)

# libctru os.h: SYSCLOCK_ARM11 = 268111856 Hz; LGR2 (3x) = 804335568 Hz.
CLOCKS = (
    ("Old 3DS appcore", 268111856),
    ("New 3DS 3x mode", 804335568),
)

# Per-tile structure-of-arrays layout (bytes per tile).
PER_TILE = {
    "cell record (sim_kernel.c)": 12,
    "render tile index/flags": 4,
    "flow field / path costs": 4,
    "power + liquid grids": 4,
    "building index": 4,
    "occupancy/mark bits": 1,
}

# Buildings are modelled as 25% of tiles; 96 bytes covers a compressed
# building record including small item/liquid slots.
BUILDING_DENSITY = 0.25
BUILDING_BYTES = 96

# Units: Mindustry caps active units per team; 200 is a deliberately generous
# client-side model. 128 bytes per unit.
UNIT_COUNT = 200
UNIT_BYTES = 128

# Effects, particles, weather and transient allocations.
EFFECTS_BYTES = 2 * MIB

# Client-side multiplayer snapshot/delta buffer (bytes per tile).
SNAPSHOT_BYTES_PER_TILE = 8

# Fixed overheads that do not scale with the map.
BASELINE = {
    "code + rodata (native port)": 10 * MIB,
    "UI, strings, content tables": 2 * MIB,
    "audio mixing + music decode": 1 * MIB,
    "network buffers (client)": 1 * MIB,
    "save/load buffers": 4 * MIB,
    "stacks (main + worker threads)": 1 * MIB,
    "Citro3D command buffers": 1 * MIB,
}

# Heap metadata / fragmentation allowance.
ALLOCATOR_OVERHEAD = 0.05

MAP_SIZES = ((96, 96), (200, 200), (500, 500))


def world_bytes(w: int, h: int) -> dict:
    tiles = w * h
    tiles_bytes = sum(PER_TILE.values()) * tiles
    buildings = int(tiles * BUILDING_DENSITY)
    building_bytes = buildings * BUILDING_BYTES
    units = UNIT_COUNT * UNIT_BYTES
    snapshots = SNAPSHOT_BYTES_PER_TILE * tiles
    total = (
        tiles_bytes
        + building_bytes
        + units
        + snapshots
        + EFFECTS_BYTES
    )
    return {
        "tiles": tiles,
        "per_tile_bytes": sum(PER_TILE.values()),
        "tile_bytes": tiles_bytes,
        "buildings": buildings,
        "building_bytes": building_bytes,
        "unit_bytes": units,
        "snapshot_bytes": snapshots,
        "effects_bytes": EFFECTS_BYTES,
        "total": total,
    }


def memory_rows() -> list[dict]:
    baseline = sum(BASELINE.values())
    rows = []
    for w, h in MAP_SIZES:
        world = world_bytes(w, h)
        requested = baseline + world["total"]
        allocated = int(requested * (1 + ALLOCATOR_OVERHEAD))
        row = {
            "map": f"{w}x{h}",
            "world_mib": world["total"] / MIB,
            "baseline_mib": baseline / MIB,
            "with_overhead_mib": allocated / MIB,
            "world": world,
            "targets": [],
        }
        for name, region in APP_REGIONS:
            fraction = allocated / region
            if fraction <= 0.70:
                verdict = "comfortable"
            elif fraction <= 0.90:
                verdict = "tight"
            else:
                verdict = "does not fit"
            row["targets"].append(
                {
                    "name": name,
                    "region_mib": region / MIB,
                    "used_fraction": fraction,
                    "headroom_mib": (region - allocated) / MIB,
                    "verdict": verdict,
                }
            )
        rows.append(row)
    return rows


def cpu_rows() -> list[dict]:
    rows = []
    for name, hz in CLOCKS:
        for hz_target in (60, 30):
            cycles = hz / hz_target
            row = {"clock": name, "hz": hz, "tick_hz": hz_target, "cycles": cycles}
            row["tiles"] = []
            for tiles in (10_000, 40_000, 100_000):
                row["tiles"].append(
                    {"tiles": tiles, "cycles_per_tile": cycles / tiles}
                )
            rows.append(row)
    return rows


def render_markdown() -> str:
    lines = []
    lines.append("# Budget model output")
    lines.append("")
    lines.append(
        "Generated by `research/java-to-native/budget_model.py`. "
        "Model only: not a 3DS measurement."
    )
    lines.append("")
    lines.append("## Memory model")
    lines.append("")
    lines.append(
        "| Map | World state | Baseline | +5% allocator | "
        "Old 3DS 64 MiB | New 3DS 124 MiB | New 3DS 178 MiB |"
    )
    lines.append("|---|---|---|---|---|---|---|")
    for row in memory_rows():
        cells = []
        for target in row["targets"]:
            cells.append(
                f"{target['used_fraction'] * 100:.1f}% "
                f"({target['verdict']}, {target['headroom_mib']:.1f} MiB free)"
            )
        lines.append(
            f"| {row['map']} | {row['world_mib']:.1f} MiB | "
            f"{row['baseline_mib']:.1f} MiB | {row['with_overhead_mib']:.1f} MiB | "
            + " | ".join(cells)
            + " |"
        )
    lines.append("")
    lines.append("Per-tile native layout:")
    lines.append("")
    lines.append("| Field group | Bytes/tile |")
    lines.append("|---|---|")
    for field, value in PER_TILE.items():
        lines.append(f"| {field} | {value} |")
    lines.append(
        f"| buildings ({BUILDING_DENSITY:.0%} of tiles x {BUILDING_BYTES} B) | "
        f"{BUILDING_DENSITY * BUILDING_BYTES:.0f} |"
    )
    lines.append(
        f"| multiplayer snapshots | {SNAPSHOT_BYTES_PER_TILE} |"
    )
    lines.append("")
    lines.append("Fixed baseline:")
    lines.append("")
    lines.append("| Item | MiB |")
    lines.append("|---|---|")
    for item, value in BASELINE.items():
        lines.append(f"| {item} | {value / MIB:.1f} |")
    lines.append(
        f"| **Total** | **{sum(BASELINE.values()) / MIB:.1f}** |"
    )
    lines.append("")
    lines.append("## Cycle budget")
    lines.append("")
    lines.append(
        "| Clock | Sim rate | Cycles/tick | Cycles per tile: 10k | 40k | 100k |"
    )
    lines.append("|---|---|---|---|---|---|")
    for row in cpu_rows():
        cells = [f"{t['cycles_per_tile']:.1f}" for t in row["tiles"]]
        lines.append(
            f"| {row['clock']} | {row['tick_hz']} Hz | {row['cycles']:.0f} | "
            + " | ".join(cells)
            + " |"
        )
    lines.append("")
    lines.append(
        "Cycle counts assume the whole appcore budget is available to the "
        "simulation, which is false for a real frame (rendering, audio, OS). "
        "Treat them as upper bounds."
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="print JSON instead of markdown")
    args = parser.parse_args()

    if args.json:
        print(
            json.dumps(
                {"memory": memory_rows(), "cpu": cpu_rows()},
                indent=2,
                default=str,
            )
        )
    else:
        print(render_markdown())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
