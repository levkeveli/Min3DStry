#!/usr/bin/env python3
"""Extract metadata from the pinned upstream base-part schematics.

Source of truth in the repo is `data/upstream-schematics.json`, extracted from
the pinned Mindustry v160.8 assets:

    core/assets/baseparts/*.msch
    commit 19a0f40d44514f4802a8b79770456e7e32e34da0

`.msch` layout: `msch`, one version byte, then a zlib stream containing
`width:u16, height:u16, tagCount:u8, (key:u16len, value:u16len)*, blockCount:u8,
blockType:u16len * blockCount`, followed by per-block placement data.

The generated console list is read-only: it shows the upstream file name,
dimensions, block count and the first few block types.

Usage:
    python3 tools/gen_schematics_catalog.py --dir /path/to/baseparts \
        --json data/upstream-schematics.json --header include/ui/schematics_catalog_data.h

    python3 tools/gen_schematics_catalog.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
import zlib
from pathlib import Path

UPSTREAM_COMMIT = "19a0f40d44514f4802a8b79770456e7e32e34da0"
UPSTREAM_SOURCE = "core/assets/baseparts .msch files"

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_JSON = ROOT / "data" / "upstream-schematics.json"
DEFAULT_HEADER = ROOT / "include" / "ui" / "schematics_catalog_data.h"


def parse_msch(path: Path) -> dict:
    raw = path.read_bytes()
    if raw[:4] != b"msch":
        raise ValueError(f"{path.name}: bad magic {raw[:4]!r}")
    data = zlib.decompress(raw[5:])
    pos = 0

    def u16() -> int:
        nonlocal pos
        value = (data[pos] << 8) | data[pos + 1]
        pos += 2
        if pos > len(data):
            raise ValueError(f"{path.name}: truncated at {pos}")
        return value

    def utf() -> str:
        nonlocal pos
        length = u16()
        if pos + length > len(data):
            raise ValueError(f"{path.name}: utf overrun at {pos} len {length}")
        value = data[pos:pos + length].decode("utf-8", "replace")
        pos += length
        return value

    width = u16()
    height = u16()
    tag_count = data[pos]
    pos += 1
    tags = {}
    for _ in range(tag_count):
        key = utf()
        tags[key] = utf()
    block_count = data[pos]
    pos += 1
    names = [utf() for _ in range(block_count)]
    return {
        "width": width,
        "height": height,
        "tags": tags,
        "blocks": block_count,
        "types": names,
    }


def extract(directory: Path) -> dict:
    entries = []
    for path in sorted(directory.glob("*.msch")):
        info = parse_msch(path)
        summary = ", ".join(info["types"][:5])
        if len(info["types"]) > 5:
            summary += ", ..."
        entries.append(
            {
                "id": path.stem,
                "name": path.stem,
                "width": info["width"],
                "height": info["height"],
                "blocks": info["blocks"],
                "tags": info["tags"],
                "summary": summary,
            }
        )
    entries.sort(
        key=lambda item: (item["name"][:1].isdigit(), item["name"].lower())
    )
    return {
        "format": 1,
        "upstream_commit": UPSTREAM_COMMIT,
        "source": UPSTREAM_SOURCE,
        "entries": entries,
    }


def _c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_header(catalog: dict) -> str:
    entries = catalog["entries"]
    lines = [
        "/* Generated by tools/gen_schematics_catalog.py; do not edit.",
        f" * Upstream: Anuken/Mindustry {catalog['upstream_commit']}",
        f" * Source: {catalog['source']}",
        " */",
        "#ifndef MIN3DSTRY_UI_SCHEMATICS_CATALOG_DATA_H",
        "#define MIN3DSTRY_UI_SCHEMATICS_CATALOG_DATA_H",
        "",
        "#include \"ui/schematics_catalog.h\"",
        "",
        f"#define M3DS_SCHEMATIC_COUNT {len(entries)}u",
        "",
        "static const M3dsSchematicRow M3DS_SCHEMATIC_TABLE[] = {",
    ]
    for entry in entries:
        lines.append(
            f"    {{{_c_string(entry['id'])}, {_c_string(entry['name'])}, "
            f"{entry['width']}u, {entry['height']}u, {entry['blocks']}u, "
            f"{_c_string(entry['summary'])}}},"
        )
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", default=None, help="Directory of upstream .msch files.")
    parser.add_argument("--json", default=str(DEFAULT_JSON))
    parser.add_argument("--header", default=str(DEFAULT_HEADER))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    json_path = Path(args.json)
    header_path = Path(args.header)

    if args.check:
        if not json_path.is_file() or not header_path.is_file():
            print("gen_schematics_catalog: missing data or header", file=sys.stderr)
            return 1
        catalog = json.loads(json_path.read_text(encoding="utf-8"))
        expected = render_header(catalog)
        actual = header_path.read_text(encoding="utf-8")
        if actual != expected:
            print(
                "gen_schematics_catalog: header is stale; rerun with --dir",
                file=sys.stderr,
            )
            return 1
        print(f"[PASS] gen_schematics_catalog: {len(catalog['entries'])} schematics")
        return 0

    if not args.dir:
        print("gen_schematics_catalog: --dir is required without --check", file=sys.stderr)
        return 2
    directory = Path(args.dir)
    if not directory.is_dir():
        print(f"gen_schematics_catalog: directory not found: {directory}", file=sys.stderr)
        return 2
    catalog = extract(directory)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(
        json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text(render_header(catalog), encoding="utf-8")
    print(
        f"gen_schematics_catalog: wrote {len(catalog['entries'])} schematics "
        f"-> {json_path}, {header_path}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
